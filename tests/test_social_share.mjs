import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=readFileSync('pricing/social/share.js','utf8').replace('export default function','function setup');
const nodes=Object.fromEntries(['share-status','native-link','native-image','copy-link','copy-caption'].map(id=>[id,{}]));
let calls=[],clipboard=[];
const navigator={share:async p=>calls.push(p),canShare:()=>true,clipboard:{writeText:async s=>clipboard.push(s)}};
const context={navigator,File:class{constructor(bytes,name,options){Object.assign(this,{bytes,name,...options});}},Uint8Array,atob:s=>Buffer.from(s,'base64').toString('binary')};
vm.createContext(context);vm.runInContext(source,context);
const data={url:'https://example.test/?garage=abc',caption:'Historical May 2021 estimate',png:'YWJj',title:'2015 Toyota'};
context.setup({parentElement:{querySelector:id=>nodes[id.slice(1)]},data});
assert.equal(calls.length,0,'No share without a click');
await nodes['native-link'].onclick();assert.equal(calls[0].url,data.url);
await nodes['native-image'].onclick();assert.equal(calls[1].files[0].name,'car-price-studio.png');
await nodes['copy-caption'].onclick();assert.equal(clipboard[0],data.caption+'\n'+data.url);
navigator.share=async()=>{throw Object.assign(new Error(),{name:'AbortError'});};
await nodes['native-link'].onclick();assert.match(nodes['share-status'].textContent,/cancelled/);
navigator.clipboard.writeText=async()=>{throw new Error();};await nodes['copy-link'].onclick();assert.match(nodes['share-status'].textContent,/Select and copy/);
navigator.share=undefined;context.setup({parentElement:{querySelector:id=>nodes[id.slice(1)]},data});
assert.equal(nodes['native-link'].disabled,true);assert.equal(nodes['native-image'].disabled,true);
console.log('Native sharing: activation, link, image, copy, cancel and unsupported fallbacks passed.');
