def _sha(file):
    with Path(file).open("rb") as h:
        return hashlib.file_digest(h,"sha256").hexdigest()


def bound_config(c):
    for name in ("family","loss","activation","optimizer","schedule"):
        if name not in c:
            raise ValueError("Missing trial configuration "+name)
    if c["family"] not in FAMILIES or c["loss"] not in LOSSES:
        raise ValueError("Unknown model or training objective")
    if c["activation"] not in ("gelu","silu") or c["optimizer"] not in ("adamw","radam"):
        raise ValueError("Unsupported activation/optimizer")
    if c["schedule"] not in ("constant","cosine","step"):
        raise ValueError("Unsupported scheduler")
    if not 0<float(c["tau"])<1 or not .01<=float(c["tail_fraction"])<=.3:
        raise ValueError("Bad quantile/tail fraction")
    if not 0<=float(c["tail_strength"])<=2 or not .005<=float(c["tail_temperature"])<=2:
        raise ValueError("Bad tail-strength/temperature")
    if not 0<float(c["beta"])<=2 or not .02<=float(c["sigma_floor"])<=.5:
        raise ValueError("Bad likelihood robustness")
    if not 1000<=float(c["usd_scale"])<=50000 or not 0<float(c["lr"])<=.01:
        raise ValueError("Bad dollar normalization or learning rate")
    if not .0<=float(c["noise"])<=.1 or not .0<=float(c["dropout"])<=.5:
        raise ValueError("Unsafe noise/dropout")
    if int(c["rank"]) not in (16,32) or int(c["project_dim"]) not in (64,96,128):
        raise ValueError("Unsupported neural rank/projector")
    if not 1<=int(c["blocks"])<=3 or int(c["width"]) not in (128,192,256):
        raise ValueError("Unsafe architecture width")
    if int(c["batch"]) not in (256,512,1024):
        raise ValueError("Unsafe CPU batch size")
    return c


class AskNetwork(nn.Module):
    """Five native deep architectures, 10 numeric + 11 categorical + Granite 384D."""
    def __init__(self,cards,initial_log_price,c):
        super().__init__()
        c=bound_config(dict(c))
        if len(cards)!=11:
            raise ValueError("11 original Ask categorical inputs required")
        self.family=c["family"]
        act=nn.GELU if c["activation"]=="gelu" else nn.SiLU
        d=int(c["project_dim"])
        self.project=nn.Sequential(
            nn.LayerNorm(DIM),nn.Linear(DIM,d),act(),nn.LayerNorm(d),
            nn.Dropout(float(c["dropout"])))
        self.register_buffer("base",torch.tensor(float(initial_log_price),dtype=torch.float32))
        if self.family=="resmlp":
            self.encoder=CarEmbedding(cards,10,d,float(c["dropout"]))
            w=int(c["width"])
            self.model=nn.Sequential(
                nn.Linear(self.encoder.width,w),nn.LayerNorm(w),act(),
                *[ResidualBlock(w,float(c["dropout"]))
                  for _ in range(int(c["blocks"]))],
                nn.LayerNorm(w),nn.Linear(w,2))
        elif self.family=="dcnv2":
            opts=dcn_config("dropout12")
            opts.update({"cross_layers":int(c["cross_layers"]),
                         "rank":int(c["rank"]),"experts":int(c["experts"]),
                         "width":int(c["width"]),"blocks":int(c["blocks"]),
                         "dropout":float(c["dropout"]),
                         "activation":c["activation"]})
            self.model=TunedDeepCross(cards,10,d,opts)
        elif self.family in ("deepfm","hofm3"):
            rank=int(c["rank"])
            self.cat_embed=nn.ModuleList([nn.Embedding(int(x),rank,padding_idx=0)
                                          for x in cards])
            self.numeric_embed=nn.Linear(10,rank)
            self.text_embed=nn.Linear(d,rank)
            w=int(c["width"])
            self.deep=nn.Sequential(
                nn.Linear(10+11*rank+d,w),nn.LayerNorm(w),act(),
                nn.Dropout(float(c["dropout"])),
                *[ResidualBlock(w,float(c["dropout"])) for _ in range(int(c["blocks"]))],
                nn.Linear(w,2))
            self.fm_strength=nn.Parameter(torch.tensor(.0005))
        elif self.family=="fttransformer":
            rank=int(c["rank"])
            self.cat_embed=nn.ModuleList([nn.Embedding(int(x),rank,padding_idx=0)
                                          for x in cards])
            self.num_weight=nn.Parameter(torch.randn(10,rank)*.02)
            self.num_bias=nn.Parameter(torch.zeros(10,rank))
            self.text_embed=nn.Linear(d,rank)
            layer=nn.TransformerEncoderLayer(
                d_model=rank,nhead=4,dim_feedforward=rank*2,
                dropout=float(c["dropout"]),batch_first=True,
                activation=F.gelu if c["activation"]=="gelu" else F.silu,
                norm_first=False)
            self.encoder=nn.TransformerEncoder(layer,num_layers=int(c["blocks"]))
            self.model=nn.Sequential(nn.LayerNorm(rank),nn.Linear(rank,2))
        else:
            raise ValueError("Unknown architecture")

    def forward(self,num,cat,embedding):
        if (num.ndim!=2 or num.shape[1]!=10
                or cat.ndim!=2 or cat.shape[1]!=11
                or embedding.ndim!=2 or embedding.shape[1]!=DIM):
            raise ValueError("Granite full-data neural input geometry differs")
        text=self.project(embedding)
        if self.family=="resmlp":
            output=self.model(self.encoder(num,cat,text))
        elif self.family=="dcnv2":
            output=self.model(num,cat,text)
        elif self.family in ("deepfm","hofm3"):
            values=[t(cat[:,i]) for i,t in enumerate(self.cat_embed)]
            token=torch.stack(values+[self.numeric_embed(num),self.text_embed(text)],dim=1)
            s1=token.sum(dim=1)
            s2=(token*token).sum(dim=1)
            fm2=.5*(s1*s1-s2)
            fm=fm2.sum(dim=1)/float(token.shape[1]*token.shape[2])
            if self.family=="hofm3":
                s3=(token**3).sum(dim=1)
                fm3=(s1**3-3*s1*s2+2*s3)/6
                fm=fm+.25*fm3.sum(dim=1)/float(token.shape[1]*token.shape[2])
            deep=torch.cat([num,*values,text],dim=1)
            output=self.deep(deep)
            output=torch.stack((output[:,0]+self.fm_strength*fm,output[:,1]),dim=1)
        else:
            tokens=torch.cat((
                num.unsqueeze(-1)*self.num_weight.unsqueeze(0)+self.num_bias.unsqueeze(0),
                torch.stack([t(cat[:,i]) for i,t in enumerate(self.cat_embed)],dim=1),
                self.text_embed(text).unsqueeze(1)),dim=1)
            output=self.model(self.encoder(tokens).mean(dim=1))
        return torch.stack((output[:,0]+self.base,output[:,1]),dim=1)


def source(features,embedding,with_matrix=True):
    features=Path(features); embedding=Path(embedding)
    meta=json.loads(features.with_suffix(".json").read_text())
    enc=json.loads((embedding/"manifest.json").read_text())
    if (meta.get("status")!="complete" or
        meta.get("cohort_sha256")!=COHORT_SHA256 or
        meta.get("full_train")!=COUNTS["train"] or
        meta.get("validation")!=COUNTS["validation"] or
        meta.get("test")!=COUNTS["test"] or
        meta.get("full_unfiltered_original_training") is not True or
        meta.get("no_target_conditioned_row_removal") is not True or
        meta.get("train_only_mileage_profiles") is not True or
        meta.get("numeric_dimension")!=10 or
        meta.get("categorical_dimension")!=11):
        raise ValueError("Not original unfiltered Ask training dataset")
    if (enc.get("status")!="complete" or
        enc.get("row_count")!=EXPECTED_TOTAL or
        enc.get("canonical_cohort_sha256")!=COHORT_SHA256 or
        enc.get("embedding_file_sha256")!=GRANITE_EMBEDDING_SHA256 or
        enc.get("model_id")!=MODEL or enc.get("model_revision")!=REVISION or
        enc.get("model_onnx_sha256")!=INT8_SHA or
        enc.get("encoder_inference")!="INT8 ONNX" or
        enc.get("test_labels_used_in_encoder") is not False):
        raise ValueError("Granite encoder is not the pinned INT8 ONNX")
    if _sha(embedding/"embeddings.npy")!=GRANITE_EMBEDDING_SHA256:
        raise ValueError("Granite ONNX embeddings SHA mismatch")
    with np.load(features,allow_pickle=False) as f:
        z={k:f[k] for k in ("num","cat","y","phase","ids")}
    emb=np.load(embedding/"embeddings.npy",mmap_mode="r")
    if (z["num"].shape!=(EXPECTED_TOTAL,10) or
        z["cat"].shape!=(EXPECTED_TOTAL,11) or
        emb.shape!=(EXPECTED_TOTAL,DIM) or emb.dtype!=np.float16):
        raise ValueError("Granite model/dataset geometry changed")
    phase=z["phase"].astype(str)
    for name,count in COUNTS.items():
        if int(sum(phase==name))!=count:
            raise ValueError("Original chronology changed "+name)
    for name in ("validation","test"):
        if id_hash(z["ids"][phase==name].astype(str))!=meta["holdout_row_sha256"][name]:
            raise ValueError("Original protected holdout identities changed")
    if (not np.isfinite(z["num"]).all() or not np.isfinite(z["y"]).all() or
        (z["y"]<=0).any() or
        len(np.unique(z["ids"]))!=EXPECTED_TOTAL):
        raise ValueError("Price labels or input features invalid")
    if with_matrix:
        return z,emb,meta,enc
    return meta,enc


def price_predictions(net,num,cat,vector,batch=2048):
    net.eval()
    result=[]
    with torch.inference_mode():
        for i in range(0,len(num),batch):
            p=net(torch.from_numpy(num[i:i+batch].astype(np.float32)),
                  torch.from_numpy(cat[i:i+batch].astype(np.int64)),
                  torch.from_numpy(np.asarray(vector[i:i+batch],dtype=np.float32)))[:,0]
            result.append(p.clamp(min=math.log(100),max=math.log(1e6)).exp().numpy())
    return np.concatenate(result).astype(np.float64)


def metrics(y,p):
    result=risk(np.asarray(y,dtype=float),np.asarray(p,dtype=float))
    result["median_abs_error_USD"]=float(np.median(np.abs(y-p)))
    result["bias_USD"]=float(np.mean(p-y))
    return result


