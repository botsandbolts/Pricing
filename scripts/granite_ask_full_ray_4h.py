def _trainable():
    from ray import tune
    class GraniteAskTrainable(tune.Trainable):
        def setup(self,config):
            self.c=bound_config(dict(config))
            torch.set_num_threads(2)
            torch.manual_seed(20261111+int(config["seed"]))
            z,emb,meta,enc=source(config["features"],config["embeddings"])
            phase=z["phase"].astype(str)
            original_train=np.flatnonzero(phase=="train")
            # No priced-based or residual-based exclusions; train-only internal stopper.
            fit=original_train[:-14777];inner=original_train[-14777:]
            if (len(fit),len(inner))!=(133000,14777):
                raise ValueError("Original complete training partition changed")
            self.num=torch.from_numpy(z["num"][fit].astype(np.float32))
            self.cat=torch.from_numpy(z["cat"][fit].astype(np.int64))
            self.emb=torch.from_numpy(np.asarray(emb[fit],dtype=np.float32))
            self.y=torch.from_numpy(np.log(z["y"][fit]).astype(np.float32))
            self.inner_num=z["num"][inner].astype(np.float32)
            self.inner_cat=z["cat"][inner].astype(np.int64)
            self.inner_emb=np.asarray(emb[inner],dtype=np.float32)
            self.inner_y=z["y"][inner].astype(np.float64)
            self.cohort_sha=meta["cohort_sha256"]
            self.embedding_sha=enc["embedding_file_sha256"]
            self.base=float(np.median(np.log(z["y"][fit])))
            self.net=AskNetwork(meta["cardinalities"],self.base,self.c)
            Opt=torch.optim.AdamW if config["optimizer"]=="adamw" else torch.optim.RAdam
            self.opt=Opt(self.net.parameters(),lr=float(config["lr"]),
                         weight_decay=float(config["wd"]),foreach=False)
            self.lr_scheduler=None
            if config["schedule"]=="cosine":
                self.lr_scheduler=torch.optim.lr_scheduler.CosineAnnealingLR(
                    self.opt,T_max=100,eta_min=.00002)
            elif config["schedule"]=="step":
                self.lr_scheduler=torch.optim.lr_scheduler.StepLR(
                    self.opt,step_size=30,gamma=.5)
            self.epoch=0
            self.best=math.inf
            self.best_epoch=0
            self.best_state=None

        def step(self):
            self.epoch+=1
            self.net.train()
            g=torch.Generator().manual_seed(20261111+self.c["seed"]*7+self.epoch)
            perm=torch.randperm(len(self.y),generator=g)
            started=time.monotonic()
            completed=0
            for ids in perm.split(int(self.c["batch"])):
                if time.time()>=float(os.environ.get("GRANITE_ASK_4H_DEADLINE","inf")):
                    break
                num=self.num[ids]
                if self.c["noise"]:
                    num=num+torch.randn_like(num)*float(self.c["noise"])
                self.opt.zero_grad(set_to_none=True)
                prediction=self.net(num,self.cat[ids],self.emb[ids])
                value=regression_loss(prediction,self.y[ids],hp(self.c),"ask")
                if not torch.isfinite(value):
                    raise ValueError("Nonfinite Granada/Granite training loss")
                value.backward()
                nn.utils.clip_grad_norm_(self.net.parameters(),float(self.c["clip"]))
                self.opt.step()
                completed+=len(ids)
            if completed < len(self.y):
                # Partial epoch at deadline must not appear as a complete checkpoint.
                return {"inner_CVaR95_absolute_USD":float(self.best if math.isfinite(self.best) else 1e14),
                        "best_inner_CVaR95_absolute_USD":float(self.best if math.isfinite(self.best) else 1e14),
                        "best_epoch":self.best_epoch,"epochs_completed":self.epoch,
                        "incomplete_deadline_epoch":True,"loss":self.c["loss"],
                        "family":self.c["family"],"test_scored":False}
            if self.lr_scheduler is not None:self.lr_scheduler.step()
            pred=price_predictions(self.net,self.inner_num,self.inner_cat,self.inner_emb)
            internal=metrics(self.inner_y,pred)
            score=float(internal["CVaR95_absolute_USD"])
            if score < self.best:
                self.best=score;self.best_epoch=self.epoch
                self.best_state={k:v.detach().clone().cpu()
                                 for k,v in self.net.state_dict().items()}
            print("GRANITE_ASK_FULL_EPOCH",json.dumps({
                "trial":self.trial_id,"epoch":self.epoch,"family":self.c["family"],
                "loss":self.c["loss"],"inner_CVaR95_USD":round(score,2),
                "best_inner_CVaR95_USD":round(self.best,2),
                "seconds":round(time.monotonic()-started,1)}),flush=True)
            return {"inner_CVaR95_absolute_USD":score,
                    "best_inner_CVaR95_absolute_USD":self.best,
                    "best_epoch":self.best_epoch,"epochs_completed":self.epoch,
                    "family":self.c["family"],"loss":self.c["loss"],
                    "completed_training_rows":len(self.y),"test_scored":False}

        def save_checkpoint(self,checkpoint_dir):
            torch.save({"state_dict":self.net.state_dict(),"best_state":self.best_state,
                "config":self.c,"epoch":self.epoch,"best":self.best,
                "best_epoch":self.best_epoch,"optimizer":self.opt.state_dict(),
                "scheduler":self.lr_scheduler.state_dict() if self.lr_scheduler else None,
                "cohort_sha256":self.cohort_sha,"embedding_sha256":self.embedding_sha,
                "base":self.base,"test_scored":False},Path(checkpoint_dir)/"checkpoint.pt")
            return checkpoint_dir

        def load_checkpoint(self,checkpoint_dir):
            state=torch.load(Path(checkpoint_dir)/"checkpoint.pt",
                             map_location="cpu",weights_only=False)
            if (state["cohort_sha256"]!=self.cohort_sha or
                    state["embedding_sha256"]!=self.embedding_sha):
                raise ValueError("Ray checkpoint came from another encoder/cohort")
            self.net.load_state_dict(state["state_dict"])
            self.opt.load_state_dict(state["optimizer"])
            if self.lr_scheduler and state["scheduler"] is not None:
                self.lr_scheduler.load_state_dict(state["scheduler"])
            self.epoch=int(state["epoch"])
            self.best=float(state["best"])
            self.best_epoch=int(state["best_epoch"])
            self.best_state=state["best_state"]
            self.base=float(state["base"])

    return GraniteAskTrainable


